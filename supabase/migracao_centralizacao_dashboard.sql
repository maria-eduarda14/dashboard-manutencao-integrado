-- ------------------------------------------------------------
-- 1. GRÁFICO DE TENDÊNCIAS
-- ------------------------------------------------------------
create table if not exists public.tendencia_notas (
    id bigint generated by default as identity primary key,
    data date not null unique,
    amarela integer not null default 0 check (amarela >= 0),
    vermelha integer not null default 0 check (vermelha >= 0),
    nd integer not null default 0 check (nd >= 0),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.dashboard_card_config (
    card_key text primary key check (card_key in ('geral', 'amarela', 'vermelha', 'nd')),
    titulo text not null check (char_length(btrim(titulo)) between 1 and 80),
    complemento text not null default '' check (char_length(complemento) <= 180),
    updated_at timestamptz not null default now()
);

alter table public.tendencia_notas enable row level security;
alter table public.dashboard_card_config enable row level security;

drop policy if exists "Leitura publica tendencia" on public.tendencia_notas;
create policy "Leitura publica tendencia"
on public.tendencia_notas
for select
to anon, authenticated
using (true);

drop policy if exists "Autenticado insere tendencia" on public.tendencia_notas;
create policy "Autenticado insere tendencia"
on public.tendencia_notas
for insert
to authenticated
with check (auth.uid() is not null);

drop policy if exists "Autenticado atualiza tendencia" on public.tendencia_notas;
create policy "Autenticado atualiza tendencia"
on public.tendencia_notas
for update
to authenticated
using (auth.uid() is not null)
with check (auth.uid() is not null);

drop policy if exists "Autenticado exclui tendencia" on public.tendencia_notas;
create policy "Autenticado exclui tendencia"
on public.tendencia_notas
for delete
to authenticated
using (auth.uid() is not null);

drop policy if exists "Leitura publica configuracao tendencia" on public.dashboard_card_config;
create policy "Leitura publica configuracao tendencia"
on public.dashboard_card_config
for select
to anon, authenticated
using (true);

drop policy if exists "Autenticado insere configuracao tendencia" on public.dashboard_card_config;
create policy "Autenticado insere configuracao tendencia"
on public.dashboard_card_config
for insert
to authenticated
with check (auth.uid() is not null);

drop policy if exists "Autenticado atualiza configuracao tendencia" on public.dashboard_card_config;
create policy "Autenticado atualiza configuracao tendencia"
on public.dashboard_card_config
for update
to authenticated
using (auth.uid() is not null)
with check (auth.uid() is not null);

insert into public.dashboard_card_config (card_key, titulo, complemento) values
    ('geral', 'Meta', 'para atingir a meta de 85%'),
    ('amarela', 'Redução Notas Amarelas', ''),
    ('vermelha', 'Redução Notas Vermelhas', ''),
    ('nd', 'Redução Notas ND', '')
on conflict (card_key) do nothing;

create or replace function public.set_tendencia_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists tendencia_notas_updated_at on public.tendencia_notas;
create trigger tendencia_notas_updated_at
before update on public.tendencia_notas
for each row execute function public.set_tendencia_updated_at();

